    "This article deals with the universalization of reason, based on some of the main bourgeois thinkers, as an inseparable element of the universalization of the juridical subject. Starting from this premise, the main purpose is to verify the possibility of extending the criticism made by Pashukanis to Hans Kelsen to the post-positivism of Robert Alexy, Which contains one of the most important instruments for the judicial application of human rights. The analysis is conducted based on elements typical of positivism in general and, after, of legal positivism. The process of impoverishment of reason is verified in a wide variety of proven positivist methodological approaches. This process is carefully studied to understand how the prevailing logic of human rights dialogues with these frameworks. A postpositivist analysis, based on one of the most relevant approaches today, based on Robert Alexy, would not be sufficient to enrich the path of reason. Hence, Pashukanis’s interpretation of Hans Kelsen can, with some refinement, also be applied to the current logic of human rights."
