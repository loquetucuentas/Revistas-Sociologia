    "The theoretical background, together with the legislative and statistical analysis conducted, makes it possible to frame the current regional governance of borders in North America as operating within a restrictive context that appears to constrain the mobility of highly skilled human capital. Specifically, the findings show an increase in TN and TD visas established through the NAFTA/USMCA trade agreements, as well as in H-1B, O-1, and J-1 visas. These trends help explain the sustained growth of highly skilled migration from Mexico to the United States since the mid-1990s and, to a much lesser extent, Canadian highly skilled migration as well. Similarly, the data examined support the hypothesis that regional inequality can generate a transfer of talent, as occurs in the case of the United States and Canada, alongside a corresponding loss of talent in Mexico. This outcome is undoubtedly related to the fact that the former two countries have developed talent-attraction policies, whereas Mexico has primarily pursued talent-retention policies."
