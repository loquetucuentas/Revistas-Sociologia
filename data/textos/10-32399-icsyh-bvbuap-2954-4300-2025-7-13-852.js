    "In this article I analyze how the actions of organized indigenous women have contributed to the construction of indigenous jurisdiction and the promotion of a dignified life within the territories of indigenous peoples. I start with a reflection on the context in which this process developed. Then, I examine the organizational process of the Provincial Network of Kichwa Women’s Organizations of Chimborazo (REDMUJCH) and, finally, I highlight the fundamental contributions made by these women. Through the organization of women on the basic of their community essence, they achieved that the 2008 Constitution of Ecuador recognizes, with constitutional rank, indigenous jurisdiction with the participation and decision of women. However, indigenous women demand a profound transformation of their own justice systems in practice to guarantee equality and eradicate gender violence. They propose an approach that not only reforms the existing structures, but also ensures their active and decisive participation in community justice processes. The exclusion of women in these spaces perpetuates patriarchal, machista relations, while weakening the legitimacy and coherence of indigenous justice systems."
