    "This article proposes an approach to the questions raised by Milei’s government regarding the future of democracy in Argentina. From a theoretical standpoint, we argue that considerations about the development of the political regime must refer to the study of the state form assumed by capital as a relation of domination, in order to conceptualize, from that level of abstraction, the concrete articulation of the state apparatus and the form of the political regime. We retrieve on Evgeny Pashukanis’ contributions to define the concepts of state form and legal form. Afterwards we reconstruct, historically, the recent transformations of the state form in Argentina over the past three decades, based on the works of Alberto Bonnet and Adrian Piva. Then, we conduct an empirical analysis of different political initiatives of the current government that affect the relations among the branches of the state and their attributions, in order to determine to what extent they exhibit features of a break with the democratic regime. Finally, we review the observed changes in the state form and argue that they point toward an “authoritarianization” of the democratic regime within the rule of law. ",
