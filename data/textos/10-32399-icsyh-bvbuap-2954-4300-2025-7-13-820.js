    "La discusión sobre la democracia remite al estudio del régimen político, el cual, a su vez, es un aspecto de la forma de Estado. El estudio de la forma de Estado supone el análisis del aparato de Estado, es decir, del conjunto de instituciones, normas, del personal y de las actividades que constituyen las funciones del Estado. Ahora bien, el Estado, en tanto modo de existencia de una relación de clase, no puede definirse al nivel de la forma de Estado ya que al definirlo de esa forma se corre el riesgo de concebir al Estado como una instancia institucional neutra capaz de ser instrumentalizada, de carácter social cambiante de acuerdo a la composición del personal que lo administre. Dado que el Estado no es simplemente un aparato o conjunto de aparatos pasibles de ser utilizados a piacere, sino una relación social entre clases objetivizada en un aparato, su definición debe partir desde un nivel de abstracción capaz de abarcar los rasgos fundamentales de aquella relación."
