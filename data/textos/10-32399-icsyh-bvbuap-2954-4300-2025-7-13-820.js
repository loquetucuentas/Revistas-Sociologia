    "Siguiendo a Marx, la relación de dominación está determinada por “la forma económica específica en la que se le extrae plustrabajo impago al productor directo”. Esto supone que “es la relación directa entre los propietarios de las condiciones de producción y los productores directos (...) en donde se encuentra el fundamento oculto de toda la estructura social, y por consiguiente, también de la forma política que presenta la relación de soberanía y dependencia. En suma, de la forma específica del estado existente en cada caso” (1991, T3 p. 1007). Dicho sencillamente, es el modo de explotación el que permite comprender el modo de dominación. Es sobre la base de las características específicas de la explotación capitalista que podemos definir al Estado como el articulador de la forma política que asume el capital en tanto relación de dominación."
