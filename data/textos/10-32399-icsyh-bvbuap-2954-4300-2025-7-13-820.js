    "Este artículo propone un abordaje de los interrogantes abiertos por el gobierno de Milei sobre el futuro de la democracia en Argentina. En términos teóricos proponemos que las consideraciones sobre el devenir del régimen político deben remitirse al estudio de la forma Estado que asume el capital en tanto relación de dominación, para pensar desde ese nivel la articulación concreta del aparato del Estado y la forma del régimen. Recuperamos los aportes de Evgeny Pashukanis para definir los conceptos de forma Estado y forma jurídica. Luego, reconstruimos históricamente las transformaciones recientes de la forma de Estado en nuestro país durante las últimas tres décadas, en base a los trabajos de Alberto Bonnet y Adrian Piva. Realizamos un análisis empírico de distintas iniciativas políticas del gobierno que afectan a las relaciones entre los poderes del Estado y a sus atribuciones, para determinar hasta qué punto muestran rasgos de ruptura con el régimen democrático. Pasamos revista de los cambios observados en la forma de Estado y sostenemos que los mismos van en el sentido de una “autoritización” del régimen democrático al interior del estado derecho."
