    "The study of violence requires understanding its everyday manifestations and the political conditions that govern life and death. In this context, the policies of death that manage the ways of dying and are exercised by the powers that be stand out, with contemporary migrations being a clear example of this. This article proposes a critical sociological analysis based on two key concepts: necropolitics and social violence, in order to interpret the complex forms of violence faced by migrant populations. This framework is complemented by the notions of violent social annihilation and hostile scenarios, culminating in the conceptual proposal of annihilation continuum. This analytical framework is applied to the case of young people forcibly displaced to the Mexico-United States border. Their journey is marked by violence from organized crime and the state’s armed forces, structures protected by policies of abandonment and discourses of institutional peace. For its empirical approach, qualitative methodologies were used through multi-sited ethnography and narrative interviews, allowing us to understand how these dynamics make the lives of migrant youth precarious."
