    "Este artículo, en formato de diálogo, recoge un intercambio colectivo entre académicxs y activistas del Sur Global que explora críticamente el concepto de decrecimiento desde América Latina. Frente a un debate dominado por perspectivas del Norte Global, se propone un enfoque situado que reconozca la pluralidad de experiencias y resistencias en los territorios latinoamericanos. Se plantea que el decrecimiento no puede ser entendido como una receta universal ni una mera reducción del PIB, sino como una herramienta crítica para desmontar las lógicas capitalistas, coloniales y patriarcales del desarrollo. A partir de experiencias encarnadas en luchas por la justicia ambiental, la autonomía comunitaria y los saberes enraizados, se aboga por un decrecimiento relacional, articulado con el Buen Vivir, la comunalidad y otras cosmovisiones. El texto destaca la urgencia de construir alternativas al “modo de vida imperial” mediante procesos de simplificación, suficiencia y prefiguración política desde abajo. Se propone una agenda de investigación y acción que cuestione las narrativas hegemónicas, reconozca las múltiples crisis en curso y habilite transiciones socioecológicas justas y pluriversales."
