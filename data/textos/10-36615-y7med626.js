   "Vissing conceptualises death as a relational, socially embedded, and transactional experience that touches not only the dying person but also their wider social networks. She frames dying and death as matters deserving more deliberate attention—“Life and death are hand-holding partners. You can’t have one without the other” (p. 2). In doing so, the book effectively draws the topic of the final farewell “from the margins back into our field of attention.” The author traces generational shifts in rituals and in the ways, we speak about death, reminding us that “pretending death isn’t coming doesn’t stop it from arriving” (p. 5). Open communication is presented as a form of care for the bereaved. Chapters devoted to relationships, information-sharing, and the dilemmas surrounding disclosure—“Disclosing that you’re dying… opens the door for them to tell you that you matter to them” (p. 40)—demonstrate the extent to which death is interwoven with social expectations, norms, and emotional labour. Vissing encourages such openness firmly yet gently: “We do our loved ones a real kindness by sharing what we want for our goodbye” (p. 5). In this way, the book affirms that a “good goodbye” is possible when it is thoughtfully considered, communicated, and prepared. It thereby aligns with the growing scholarship on death literacy (Leonard et al., 2022; Noonan, 2021) and resonates with contemporary death-positivity movements—a term coined by mortician Caitlin Doughty in 2011, rooted in the 1970s hospice movement and challenging the medicalisation and sanitisation of death (",
