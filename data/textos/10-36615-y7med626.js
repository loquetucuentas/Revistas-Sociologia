   "The book constitutes a valuable contribution to the sociology of death, palliative care, and community practice. It provides not only analytical insight but also practical tools that foster autonomy, reflection, and open dialogue about end-of-life issues. Its emphasis on individual—and therefore diverse—capacities, needs, and practices is reinforced through the inclusion of personal testimonies that illuminate the heterogeneity of people’s experiences and desires. Vissing presents death as a universal human experience that, if left unconsidered, may generate conflict, anger, and distress. She underscores that our death affects the lives of others just as theirs have shaped ours, to reduce suffering and promote well-being. Ultimately, Vissing succeeds in drawing the topic of the final farewell back into view and demonstrates that planning for death can be a profoundly human, relational, and empowering process."
