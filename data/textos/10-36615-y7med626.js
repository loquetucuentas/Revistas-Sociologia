   "Although the book provides a practical, empowering, and individualised guide to planning one’s own “good goodbye,” a significant portion is also devoted to critiquing the commercialisation of the funeral industry—“the mortician is just the gatekeeper to a sprawling, profit-driven industry” (p. 118). When placed alongside scholarship that explicitly examines the economisation of dying (",
