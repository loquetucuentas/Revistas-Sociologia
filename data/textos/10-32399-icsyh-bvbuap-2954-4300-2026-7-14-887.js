    "En las primeras décadas del siglo XXI, la forma Estado continúa presentándose como el horizonte incuestionable de la política. Aun en medio de la globalización neoliberal, de la fragmentación de soberanías nacionales y de la proliferación de dispositivos transnacionales de gobierno, la idea de que toda organización colectiva debe encontrar su destino en alguna modalidad de estatalidad -sea liberal, social, desarrollista o progresista- persiste como supuesto dominante. Sin embargo, de manera recurrente y obstinada, emergen experiencias sociales que cuestionan ese presupuesto: formas de autogobierno comunitario, asambleas territoriales, confederaciones sin Estado, movimientos horizontales, comunes urbanos y rurales que rehúsan delegar su capacidad política en instancias separadas de mando. Lejos de ser anomalías pasajeras, estas experiencias reactivan una vieja pregunta: ¿es posible una política más allá del Estado?"
