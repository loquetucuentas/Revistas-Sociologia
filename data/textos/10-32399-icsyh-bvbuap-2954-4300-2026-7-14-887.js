    "This article examines the possibility of non-state politics through the historical antagonism between State and community. It begins with a critique of the State as a form of rule that produces legible and governable subjects, and recovers genealogies of societies that have organized collective life without permanent structures of domination, from Pierre Clastres and James C. Scott to the modern experience of the Paris Commune. On this basis, contemporary re-openings of bottom-up organization -Zapatismo, Kurdish democratic confederalism, and urban commonsare analyzed as communal constellations that reactivate long memories of self-government. Finally, the article explores the forces of state and capitalist closure these experiences confront, as well as their enduring capacity to reopen political imagination. Rather than finished models, these practices reveal non-state politics as a recurrent historical possibility rather than a future utopia."
