    "The work of Bob Jessop and the development of Joachim Hirsch’s materialist theory of the state provided the foundational framework for an unexpected encounter—until the 1970s—between Poulantzas and Pashukanis. This article revisits their theoretical confrontation, emphasizing Poulantzas’s abandonment of the role of commodity circulation in his explanation of the capitalist state, and Pashukanis’s neglect of production in his derivation of the state. The confrontation between these two authors pursues two primary objectives. First, it seeks to deepen the understanding of their respective state theories, clarifying their specific differences, areas of agreement, and, most importantly, the contributions each makes to the comprehension of the capitalist state. Second, it aims to establish—a point of departure derived from the confrontation between their works—a new starting point for the study of the capitalist state: the unity of production and circulation that structures the relation of exploitation as a process of surplus-value production, and its effects on the structure of class power."
