    "In recent years, the fashion industry in Mexico has embraced discourses that advocate for body diversity and the redefinition of canonical beauty standards. By promoting new forms of representation within the field, the industry aims to challenge the norms associated with these standards in Mexico. This article analyzes how these transformations are experienced by young people involved in the fashion industry in Mexico City. Based on ethnographic research that included interviews with models and other industry professionals, as well as observation in various fashion production settings, the study examines the labor issues, body expectations, and working conditions that shape the subjective experiences of these young people. The analysis shows that, while these discourses expand certain possibilities for body representation, they also coexist with persistent dynamics of job precariousness and specific aesthetic demands that shape young people’s experiences and subjectivities within the fashion industry."
