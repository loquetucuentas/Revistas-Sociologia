    "The article is situated within a theoretical framework that addresses the structural and conjunctural inequalities shaping contemporary youth, problematizing education as a right in constant dispute. Its specific objective is to analyze the impact of Educational Component Policies (ECP) on the educational trajectories of Argentine youth navigating the upper secondary school cycle in contexts of socio-educational vulnerability. The methodology employed is quantitative, with a longitudinal design that allowed for the tracking of the school trajectories of a single cohort during the years 2022, 2023, and 2024 in three urban areas of Argentina: Greater Buenos Aires, Río Cuarto (Córdoba), and Salta. The main findings indicate that while ECPs effectively target the most vulnerable sectors and contribute to sustaining educational engagement, their receipt is recurrently associated with intermittent and even dropout trajectories. This evidence suggests that, despite their relevance as buffers against structural inequality, ECPs alone are insufficient to ensure educational trajectories comparable to those of sectors in better socio-educational conditions, highlighting the need to strengthen the articulation between social policy and educational policy."
