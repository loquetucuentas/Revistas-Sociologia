    "El artículo se inscribe en un marco teórico que aborda las desigualdades estructurales y coyunturales que atraviesan las juventudes contemporáneas problematizando la educación como un derecho en constante disputa. Su objetivo específico es analizar la incidencia de las políticas de componente educativo (PCE) en las trayectorias educativas de jóvenes argentinos que transitan el ciclo orientado de la escuela secundaria, en contextos de vulnerabilidad socioeducativa. La metodología empleada es cuantitativa, con un diseño longitudinal que permitió acompañar los recorridos escolares de una misma cohorte durante los años 2022, 2023 y 2024 en tres aglomerados de Argentina: Conurbano Bonaerense, Río Cuarto (Córdoba) y Salta. Los principales resultados indican que, si bien las PCE logran una efectiva focalización en los sectores más vulnerabilizados y contribuyen a sostener el vínculo educativo, su recepción se asocia de manera recurrente con trayectorias intermitentes e incluso abandónicas. Esta evidencia sugiere que, pese a su relevancia como dispositivos de amortiguación frente a la desigualdad estructural, las PCE resultan insuficientes por si solas para garantizar trayectorias educativas equiparables a las de los sectores en mejores condiciones socioeducativas, evidenciando la necesidad de fortalecer la articulación entre la política social y la política educativa."
