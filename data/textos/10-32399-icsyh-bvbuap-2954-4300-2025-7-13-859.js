    "Posteriormente en “El sufrimiento y su validación social: sobre el trabajo abstracto”, Werner Bonefeld profundiza en el doble carácter del trabajo en Marx, como trabajo concreto y trabajo abstracto, un concepto que Holloway considera fundamental para comprender al capitalismo. Bonefeld enfatiza que el trabajo abstracto no es una categoría natural o fisiológica, sino puramente social, una forma que opera como compulsión económica silenciosa. A diferencia de algunas interpretaciones que ven al trabajo abstracto como un gasto de energía humana transhistórico, Bonefeld, en línea con la crítica del valor que busca develar las formas “valor”, “mercancía”, “dinero” y “capital” como relaciones sociales invertidas, subraya su carácter socialmente mediado, donde el tiempo de trabajo de los individuos se valida sólo como “tiempo de trabajo universal objetivado” a través del intercambio. Holloway, por su parte, interpreta al trabajo concreto como algo que adquiere un carácter abstracto en el capitalismo debido a su creciente simplificación y su tecnologización. La contribución de Bonefeld explica como esta validación social convierte al trabajo vivo socialmente inválido en capital obsoleto y mano de obra redundante, revelando así el carácter implacable de la competencia capitalista como una coerción social impersonal y abstracta propia del capitalismo que afirma las leyes inmanentes de este modo históricamente específico de producción."
