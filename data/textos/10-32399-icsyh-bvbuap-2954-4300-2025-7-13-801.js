    "El mercado de trabajo suele ser definido como ese espacio donde confluyen la oferta y la demanda de mano de obra, o bien, donde se encuentra el trabajador con el empleador, determinando salarios, condiciones laborales y niveles de empleo (Becker, 1964; Borjas, 2016). Se podría decir, entonces, que el mercado de trabajo, en palabras de Karl Marx, es donde “el capitalista compra una determinada cantidad de fuerza de trabajo productiva”, pero sin perder de vista que la competencia entre compradores y vendedores, es decir, la relación entre la demanda y la oferta, no está libre de todo tipo de tensiones, pues también genera el desempleo, la informalidad, la desigualdad salarial y la precarización laboral (Marx, 1849: 23, 27). Las crisis económicas agravan estos problemas, sobre todo porque en estos periodos se contrae la demanda y aumenta la incertidumbre empresarial, lo que reduce la creación de empleos, produce despidos masivos y lleva a la expansión de trabajos informales y temporales."
