    "In this text I call bio-mediated affective communication to the articulation of organic resources for the processing and responding of information involved in material processes connecting human bodies, operating in parallel to communicative processes mediated symbolically. On the first section I focus on communicative capacities of bodies expressed through imitation, suggestion, mimesis and contagion in their different modalities; I discuss the theoretical heritage of such concepts and frame them as forms of transmission of affect within contemporary affect studies. On the last section I show two concrete racial effects of these bio-mediated communication in the context of the affective production of colonization: brown bodies´ affective registers -or forms of being- and relational propensities -or forms of doing- towards themselves and other racial groups, particularly regarding black and white bodies. The text contributes towards an understanding of racial relations and the subjectivities emerging from such relations as events with affective, material and organic bases."
